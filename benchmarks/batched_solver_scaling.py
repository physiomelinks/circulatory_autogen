"""Scaling of the batched CellML solvers on a colony of N unconnected cells.

The model is a module array of N copies of AdaptOrDeity's fermenter cell (``resources/fermenter_colony``, one
block of 23 states per cell). Every cell runs the same glucose protocol: 60 s at 0.1 mM at its membrane, 120 s at
50 mM, 120 s at 0.1 mM (three sub-experiments, outputs each second). Each solver runs it once to warm up and is
timed on the best of the next three; setup (generating C and building the library, cached after the first time) is
reported apart.

    python benchmarks/batched_solver_scaling.py --jobs 4              # N = 2..512, 1 and 8 threads
    python benchmarks/batched_solver_scaling.py --cells 2,16 --threads 1 --myokit-max-cells 8
    python benchmarks/batched_solver_scaling.py --accuracy-cells 16   # errors against a tight reference

Results go to ``benchmarks/_results/batched_solver_scaling/`` (JSON and a Markdown table). CVODES_batched_c needs
SUNDIALS 6 or later (``SUNDIALS_DIR``); without it its rows are skipped.
"""
import argparse
import json
import os
import platform
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
LIBRARY = os.path.join(HERE, 'resources', 'fermenter_colony', 'module_library')
OUT = os.path.join(HERE, '_results', 'batched_solver_scaling')
MODULE = {'module_type': 'generic_adaptive_cell', 'module_subtype': 'fermenter', 'parameterisation': 'default'}
GLUCOSE = 'C_glc_e_mod_membrane_face'
SIM_TIMES = [60.0, 120.0, 120.0]
GLUCOSE_MM = [0.1, 50.0, 0.1]

#: (label, solver, solver_info)
SOLVERS = [
    ('BE_batched_c, TR-BDF2, rtol 1e-4', 'BE_batched_c', {'method': 'trbdf2', 'rtol': 1e-4}),
    ('BE_batched_c, TR-BDF2, rtol 1e-6', 'BE_batched_c', {'method': 'trbdf2', 'rtol': 1e-6}),
    ('CVODES_batched_c, rtol 1e-6', 'CVODES_batched_c', {'rtol': 1e-6}),
]
MYOKIT = ('CVODE_myokit, rtol 1e-6', 'CVODE_myokit', {'rtol': 1e-6, 'atol': 1e-8})
REFERENCE = ('CVODES_batched_c, rtol 1e-10, atol 1e-12', 'CVODES_batched_c', {'rtol': 1e-10, 'atol': 1e-12})


def write_colony_inputs(n, resources_dir):
    """Write the module array of ``n`` fermenter cells (``cell_0`` .. ``cell_{n-1}``) and an empty parameters
    file (each cell takes its parameterisation's parameters) as ``colony_{n}_*``; returns the file prefix."""
    prefix = f'colony_{n}'
    os.makedirs(resources_dir, exist_ok=True)
    records = [{'name': f'cell_{i}', **MODULE, 'inp_instances': [], 'out_instances': []} for i in range(n)]
    with open(os.path.join(resources_dir, f'{prefix}_module_array.json'), 'w') as f:
        json.dump(records, f, indent=1)
    with open(os.path.join(resources_dir, f'{prefix}_parameters.json'), 'w') as f:
        json.dump({'schema_version': 1}, f)
    return prefix


def generate_colony(n, work_dir):
    """The colony's CellML file (generated by CA from the module array), under ``work_dir``.

    Generation skips its check that the model runs on CVODE_myokit: compiling the whole colony for Myokit takes
    13 minutes at 64 cells, and the batched solvers build and run the model anyway."""
    from libcuflynx.generators.CVSCellMLGenerator import CVS0DCellMLGenerator
    from libcuflynx.scripts.script_generate_with_new_architecture import generate_with_new_architecture
    resources = os.path.join(work_dir, 'resources')
    generated = os.path.join(work_dir, 'generated_models')
    prefix = write_colony_inputs(n, resources)
    path = os.path.join(generated, prefix, f'{prefix}.cellml')
    if not os.path.exists(path):
        check = CVS0DCellMLGenerator._validate_with_myokit
        CVS0DCellMLGenerator._validate_with_myokit = lambda self, cellml_path: (True, None)
        try:
            ok = generate_with_new_architecture(False, {
                'file_prefix': prefix, 'input_param_file': f'{prefix}_parameters.json', 'model_type': 'cellml',
                'solver': 'CVODE_myokit', 'resources_dir': resources, 'generated_models_dir': generated,
                'module_library_dirs': [LIBRARY], 'use_builtin_modules': False, 'DEBUG': False})
        finally:
            CVS0DCellMLGenerator._validate_with_myokit = check
        assert ok, f'generating the colony of {n} cells failed'
    return path


def protocol(n):
    """Every cell's membrane glucose stepped through GLUCOSE_MM, one sub-experiment each."""
    return {'pre_times': [0.0], 'sim_times': [list(SIM_TIMES)],
            'params_to_change': {f'cell_{i}/{GLUCOSE}': [list(GLUCOSE_MM)] for i in range(n)}}


def run(model, solver, solver_info, n, threads, build_dir, observed):
    """Wall times of setup and of the timed protocol run, and ``observed`` each second of it."""
    from libcuflynx.protocol_runners.protocol_executor import ProtocolExecutor
    from libcuflynx.solver_wrappers import get_simulation_helper
    info = dict(solver_info)
    if solver != 'CVODE_myokit':
        info.update(threads=threads, build_dir=build_dir)
    t0 = time.perf_counter()
    helper = get_simulation_helper(model, solver, 'cellml', dt=1.0, sim_time=SIM_TIMES[0], solver_info=info)
    setup = time.perf_counter() - t0
    walls = []
    for _ in range(4):
        t0 = time.perf_counter()
        ok, by_sub, _, _ = ProtocolExecutor(helper).run_protocol(protocol(n), result_variables=[observed])
        walls.append(time.perf_counter() - t0)
        assert ok, f'{solver} failed on {n} cells'
    series = np.column_stack([np.concatenate([np.ravel(by_sub[(0, s)][0][k]) if s == 0 else
                                              np.ravel(by_sub[(0, s)][0][k])[1:] for s in range(len(SIM_TIMES))])
                              for k in range(len(observed))])
    helper.close_simulation()
    return {'setup_s': setup, 'run_s': min(walls[1:]), 'series': series}


def build(model, solver, build_dir):
    """Build (or load from the cache) ``solver``'s library for ``model``: the setup wall time, and the states of
    cell 0 as the batched solvers name them."""
    from libcuflynx.solver_wrappers import get_simulation_helper
    t0 = time.perf_counter()
    helper = get_simulation_helper(model, solver, 'cellml', dt=1.0, sim_time=1.0, solver_info={'build_dir': build_dir})
    setup = time.perf_counter() - t0
    names = [s for s in helper.state_names if s.startswith('cell_0_module/')]
    helper.close_simulation()
    return setup, names


def _timed_build(model, solver, build_dir):
    try:
        return build(model, solver, build_dir)[0]
    except RuntimeError as exc:
        return exc


def prebuild(models, solvers, build_dir, jobs):
    """Each solver's library for each colony (``models``: {N: CellML path}), built ``jobs`` at a time, largest
    first, into the cache; {(N, solver): setup seconds}. A failed build is left to the timing loop to report."""
    from concurrent.futures import ProcessPoolExecutor
    work = sorted(((n, solver) for n in models for solver in solvers), key=lambda k: -k[0])
    with ProcessPoolExecutor(jobs) as pool:
        futures = {key: pool.submit(_timed_build, models[key[0]], key[1], build_dir) for key in work}
        out = {}
        for (n, solver), f in futures.items():
            r = f.result()
            if not isinstance(r, Exception):
                out[n, solver] = r
                print(f'{n:4d} cells  {solver} built in {r:.1f} s ({jobs} at a time)', flush=True)
    return out


def worst_error(series, reference):
    """Largest difference over time of any observed variable, relative to the largest size it reaches."""
    scale = np.maximum(np.max(np.abs(reference), axis=0), 1e-12)
    return float(np.max(np.max(np.abs(series - reference), axis=0) / scale))


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--cells', default='2,4,8,16,32,64,128,256,512')
    p.add_argument('--threads', default='1,8')
    p.add_argument('--myokit-max-cells', type=int, default=8,
                   help='run CVODE_myokit up to this many cells (its build grows fast with N); 0 for none')
    p.add_argument('--accuracy-cells', type=int, default=16, help='colony size of the accuracy table; 0 for none')
    p.add_argument('--jobs', type=int, default=1,
                   help='build the libraries this many at a time before timing (setup grows ~4x per doubling of N)')
    p.add_argument('--out', default=OUT)
    args = p.parse_args(argv)
    from libcuflynx.generators.cpp.batched import BatchedBuildError
    cells = [int(c) for c in args.cells.split(',')]
    threads = [int(t) for t in args.threads.split(',')]
    os.makedirs(args.out, exist_ok=True)
    build_dir = os.path.join(args.out, 'build')
    simulated = sum(SIM_TIMES)
    load = os.getloadavg() if hasattr(os, 'getloadavg') else None
    results = {'machine': f'{platform.processor() or platform.machine()}, {os.cpu_count()} logical CPUs',
               'load_at_start': load, 'simulated_s': simulated, 'scaling': [], 'accuracy': []}
    results['setup'] = []
    results['build_jobs'] = args.jobs
    solvers = list(SOLVERS)
    models = {}
    for n in cells:
        t0 = time.perf_counter()
        models[n] = generate_colony(n, os.path.join(args.out, f'colony_{n}'))
        results['setup'].append({'cells': n, 'solver': 'CA generation (CellML)', 'setup_s': time.perf_counter() - t0})
        print(f'{n:4d} cells  CellML generated in {results["setup"][-1]["setup_s"]:.1f} s', flush=True)
    prebuilt = prebuild(models, [s for s in dict.fromkeys(s[1] for s in solvers)], build_dir, args.jobs) \
        if args.jobs > 1 else {}

    results['load_before_timing'] = os.getloadavg() if hasattr(os, 'getloadavg') else None
    for n in cells:
        model = models[n]
        observed = None
        for solver in dict.fromkeys(s[1] for s in solvers):
            try:
                setup, names = build(model, solver, build_dir)
            except BatchedBuildError as exc:     # CVODES_batched_c without SUNDIALS
                print(f'{solver} skipped: {exc}')
                solvers = [s for s in solvers if s[1] != solver]
                continue
            setup = prebuilt.get((n, solver), setup)
            observed = observed or names[:1]
            results['setup'].append({'cells': n, 'solver': solver, 'setup_s': setup})
            print(f'{n:4d} cells  {solver} setup (generate C, build) {setup:.1f} s', flush=True)
        rows = [(label, solver, info, t) for label, solver, info in solvers for t in threads]
        if n <= args.myokit_max_cells:
            rows.append((*MYOKIT, 1))
        for label, solver, info, t in rows:
            r = run(model, solver, info, n, t, build_dir, observed)
            row = {'cells': n, 'solver': label, 'threads': t, 'setup_s': r['setup_s'], 'run_s': r['run_s'],
                   'x_real_time': simulated / r['run_s']}
            results['scaling'].append(row)
            print(f"{n:4d} cells  {label:36s} {t} thread(s)  setup {r['setup_s']:7.2f} s  "
                  f"run {r['run_s']:8.4f} s  {row['x_real_time']:9.0f}x real time", flush=True)

    if args.accuracy_cells:
        n = args.accuracy_cells
        model = generate_colony(n, os.path.join(args.out, f'colony_{n}'))
        observed = build(model, 'BE_batched_c', build_dir)[1]
        reference = run(model, REFERENCE[1], REFERENCE[2], n, 1, build_dir, observed)['series']
        for label, solver, info in solvers + ([MYOKIT] if n <= max(args.myokit_max_cells, 16) else []):
            r = run(model, solver, info, n, 1, build_dir, observed)
            err = worst_error(r['series'], reference)
            results['accuracy'].append({'cells': n, 'solver': label, 'worst_relative_error': err})
            print(f'{n} cells  {label:36s} worst error {err:.2e} (cell 0, every state, each second)', flush=True)

    results['load_at_end'] = os.getloadavg() if hasattr(os, 'getloadavg') else None
    with open(os.path.join(args.out, 'results.json'), 'w') as f:
        json.dump(results, f, indent=1)
    with open(os.path.join(args.out, 'results.md'), 'w') as f:
        f.write(markdown(results))
    print(markdown(results))


def markdown(results):
    """The scaling table (run wall time and x real time per colony size) and the accuracy table."""
    keys = sorted({(r['solver'], r['threads']) for r in results['scaling']},
                  key=lambda k: ([s[0] for s in SOLVERS + [MYOKIT]].index(k[0]), k[1]))
    cells = sorted({r['cells'] for r in results['scaling']})
    by = {(r['solver'], r['threads'], r['cells']): r for r in results['scaling']}
    lines = [f"{results['simulated_s']:.0f} simulated s; run wall time (x real time). {results['machine']}; "
             f"load average before timing {results.get('load_before_timing', results['load_at_start'])}.", '',
             '| solver | threads | ' + ' | '.join(f'{n} cells' for n in cells) + ' |',
             '|---|---|' + '---|' * len(cells)]
    for solver, t in keys:
        cols = []
        for n in cells:
            r = by.get((solver, t, n))
            cols.append(f"{r['run_s']:.3g} s ({r['x_real_time']:.0f}x)" if r else '')
        lines.append(f'| {solver} | {t} | ' + ' | '.join(cols) + ' |')
    lines += ['', 'Setup, the first time: CA generates the CellML from the module array; each batched solver generates '
              'C and builds it (about 0.1 s once cached'
              + (f"; built {results['build_jobs']} at a time" if results.get('build_jobs', 1) > 1 else '')
              + '); CVODE_myokit compiles on every load.', '',
              '| cells | ' + ' | '.join(sorted({r['solver'] for r in results['setup']})) + ' | CVODE_myokit |',
              '|---|' + '---|' * (len({r['solver'] for r in results['setup']}) + 1)]
    for n in cells:
        setup = {r['solver']: r['setup_s'] for r in results['setup'] if r['cells'] == n}
        myokit = [r['setup_s'] for r in results['scaling'] if r['cells'] == n and r['solver'] == MYOKIT[0]]
        lines.append(f'| {n} | ' + ' | '.join(f'{setup[k]:.1f} s' if k in setup else '' for k in sorted(
            {r['solver'] for r in results['setup']})) + ' | ' + (f'{myokit[0]:.1f} s' if myokit else '') + ' |')
    if results['accuracy']:
        lines += ['', f"Worst error of cell 0's states, each second, against {REFERENCE[0]} "
                      f"({results['accuracy'][0]['cells']} cells):", '', '| solver | worst relative error |',
                  '|---|---|']
        lines += [f"| {r['solver']} | {r['worst_relative_error']:.1e} |" for r in results['accuracy']]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    sys.exit(main())
