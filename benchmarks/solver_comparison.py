"""Run the same CellML models through every installed solver backend, at equal settings.

Backends (each skipped, with the reason, when it is not installed):

- ``myokit``      CVODE_myokit       (installed with libcuflynx)
- ``libopencor``  CVODE_libopencor   (``pip install "libcuflynx[libopencor]"``, Python 3.12+)
- ``casadi``      casadi_integrator, method cvodes, JIT off (``pip install "libcuflynx[casadi]"``)
- ``casadi_jit``  the same with CasADi's JIT compilation of the model functions (needs a C compiler)

Every backend gets the same relative and absolute tolerance, maximum step and output grid, and
starts from the model's initial values (no warm-up: CasADi's helper has none). For each model
and backend it reports:

- ``setup_s``   building the helper: flattening/compiling the model (and, for CasADi, generating
  its Python model from the CellML first);
- ``first_run_s`` the first run, which includes any work deferred to it;
- ``run_median_s`` the median of ``--repeats`` further runs, each from the initial values;
- ``steps`` / ``rhs_evals`` CVODE's step and right-hand-side counts, where the backend exposes
  them (Myokit);
- ``max_rel_err`` / ``worst_state`` the largest difference from the reference backend over every
  state, relative to that state's largest magnitude, and the state it is in.

    python benchmarks/solver_comparison.py                         # built-in models, all backends
    python benchmarks/solver_comparison.py --models lotka_volterra --backends libopencor
    python benchmarks/solver_comparison.py --model-file my_model.cellml --sim-time 10

Results go to ``--out`` (default ``benchmarks/_results/solver_comparison/``) as
``solver_comparison.json`` and ``solver_comparison.md``.
"""
import argparse
import contextlib
import importlib.util
import io
import json
import os
import platform
import shutil
import statistics
import sys
import tempfile
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_OUT = os.path.join(HERE, '_results', 'solver_comparison')

#: name -> (description, how the CellML is made, default sim_time in seconds)
MODELS = {
    'lotka_volterra': ('Lotka-Volterra (tests/test_inputs)',
                       ('file', os.path.join(REPO, 'tests', 'test_inputs',
                                             'Lotka_Volterra_forced.cellml')), 20.0),
    'goodwin': ('Goodwin 1965 oscillator, PMR CellML 1.0 (resources/)',
                ('file', os.path.join(REPO, 'resources', 'Goodwin.cellml')), 50.0),
    '3compartment': ('3compartment circulation, stiff, generated by CA',
                     ('generate', '3compartment', '3compartment_parameters.json'), 5.0),
}

#: name -> (description, module that must import, solver, model_type, extra solver_info)
BACKENDS = {
    'myokit': ('CVODE_myokit', 'myokit', 'CVODE_myokit', 'cellml', {}),
    'libopencor': ('CVODE_libopencor', 'libopencor', 'CVODE_libopencor', 'cellml', {}),
    'casadi': ('casadi_integrator cvodes, JIT off', 'casadi', 'casadi_integrator',
               'casadi_python', {'method': 'cvodes'}),
    'casadi_jit': ('casadi_integrator cvodes, JIT on', 'casadi', 'casadi_integrator',
                   'casadi_python', {'method': 'cvodes', 'options': {
                       'jit': True, 'compiler': 'shell', 'jit_options': {'flags': ['-O2']}}}),
}


def available_backends(names):
    """{name: None} for each backend that can run, {name: reason} for each that cannot."""
    status = {}
    for name in names:
        module = BACKENDS[name][1]
        if importlib.util.find_spec(module) is None:
            status[name] = f'{module} is not installed'
        elif name == 'casadi_jit' and shutil.which('cc') is None and shutil.which('gcc') is None:
            status[name] = 'no C compiler for the JIT'
        else:
            status[name] = None
    return status


def solver_info_for(backend, rtol, atol, max_step):
    """The same tolerances and maximum step, under each backend's own key names."""
    _, _, solver, _, extra = BACKENDS[backend]
    if solver == 'casadi_integrator':
        info = {'reltol': rtol, 'abstol': atol, 'max_step_size': max_step,
                'max_num_steps': 100000}
    else:
        info = {'rtol': rtol, 'atol': atol, 'MaximumStep': max_step}
        if solver == 'CVODE_libopencor':
            info['MaximumNumberOfSteps'] = 100000
    info.update(extra)
    info['solver'] = solver
    return info


@contextlib.contextmanager
def quiet(enabled=True):
    """Silence the helpers' progress printing while timing."""
    if not enabled:
        yield
        return
    with contextlib.redirect_stdout(io.StringIO()):
        yield


def cellml_for(name, work_dir):
    """The CellML file of a built-in model (generated into ``work_dir`` when it needs to be)."""
    how = MODELS[name][1]
    if how[0] == 'file':
        target = os.path.join(work_dir, name, os.path.basename(how[1]))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copy(how[1], target)
        return target
    _, prefix, parameters = how
    from libcuflynx.scripts.script_generate_with_new_architecture import \
        generate_with_new_architecture
    from libcuflynx.utilities.utility_funcs import get_default_inp_data_dict
    inp = get_default_inp_data_dict(prefix, parameters, os.path.join(REPO, 'resources'))
    inp.update(generated_models_dir=os.path.join(work_dir, 'generated'), DEBUG=True,
               model_type='cellml')
    if not generate_with_new_architecture(False, inp):
        raise RuntimeError(f'generating {prefix} failed')
    return os.path.join(work_dir, 'generated', prefix, f'{prefix}.cellml')


def casadi_model_for(cellml_path, work_dir):
    """The CasADi Python model generated from ``cellml_path``."""
    from libcuflynx.generators.PythonGenerator import PythonGenerator
    stem = os.path.splitext(os.path.basename(cellml_path))[0]
    out = os.path.join(work_dir, f'{stem}_casadi')
    return PythonGenerator(cellml_path, output_dir=out, module_name=stem,
                           casadi_compat=True).generate()


def state_names(cellml_path):
    """The model's states as ``component/variable``, which every backend resolves."""
    import libcuflynx.utilities.libcellml_helper_funcs as cellml
    import libcellml
    model = cellml.parse_model(cellml_path, False)
    importer = cellml.resolve_imports(model, os.path.dirname(os.path.abspath(cellml_path)), False)
    flat = cellml.flatten_model(model, importer)
    analyser = libcellml.Analyser()
    analyser.analyseModel(flat)
    analysed = analyser.analyserModel()
    names = []
    for i in range(analysed.stateCount()):
        variable = analysed.state(i).variable()
        names.append(f'{variable.parent().name()}/{variable.name()}')
    return names


def solver_stats(helper):
    """CVODE's step and right-hand-side evaluation counts for the last run, where exposed."""
    simulation = getattr(helper, 'simulation', None)
    if simulation is not None and hasattr(simulation, 'last_number_of_steps'):
        return {'steps': int(simulation.last_number_of_steps()),
                'rhs_evals': int(simulation.last_number_of_evaluations())}
    return {'steps': None, 'rhs_evals': None}


def run_backend(backend, cellml_path, work_dir, outputs, args):
    """Time one backend on one model; returns (row, results by output name)."""
    from libcuflynx.solver_wrappers import get_simulation_helper
    _, _, solver, model_type, _ = BACKENDS[backend]
    info = solver_info_for(backend, args.rtol, args.atol, args.max_step)

    started = time.perf_counter()
    with quiet(not args.verbose):
        model_path = (casadi_model_for(cellml_path, work_dir) if model_type == 'casadi_python'
                      else cellml_path)
        helper = get_simulation_helper(model_path=model_path, solver=solver,
                                       model_type=model_type, dt=args.dt,
                                       sim_time=args.sim_time, solver_info=info, pre_time=0.0)
    setup = time.perf_counter() - started

    def one_run():
        with quiet(not args.verbose):
            helper.reset_and_clear()
            begin = time.perf_counter()
            if not helper.run():
                raise RuntimeError(f'{backend} failed to integrate {cellml_path}')
            return time.perf_counter() - begin

    first = one_run()
    stats = solver_stats(helper)
    results = dict(zip(outputs, helper.get_results(outputs, flatten=True)))
    repeats = [one_run() for _ in range(args.repeats)]
    if hasattr(helper, 'close_simulation'):
        helper.close_simulation()
    row = {'setup_s': setup, 'first_run_s': first, 'run_median_s': statistics.median(repeats),
           'repeats': args.repeats, **stats}
    return row, {name: np.asarray(values, dtype=float) for name, values in results.items()}


def max_relative_error(results, reference):
    """(largest relative difference over every state, the state it is in)."""
    worst, worst_name = 0.0, None
    for name, ref in reference.items():
        values = results[name]
        n = min(len(values), len(ref))
        scale = max(float(np.max(np.abs(ref[:n]))), 1e-300)
        error = float(np.max(np.abs(values[:n] - ref[:n]))) / scale
        if error > worst:
            worst, worst_name = error, name
    return worst, worst_name


def compare_model(label, cellml_path, backends, args, work_dir):
    outputs = state_names(cellml_path)
    rows, traces = {}, {}
    for backend in backends:
        try:
            rows[backend], traces[backend] = run_backend(backend, cellml_path, work_dir,
                                                         outputs, args)
        except Exception as exc:  # noqa: BLE001 - one backend failing should not stop the rest
            rows[backend] = {'error': f'{type(exc).__name__}: {exc}'}
        print(f'  {backend}: {rows[backend]}', flush=True)
    reference = next((b for b in [args.reference] + list(backends) if b in traces), None)
    for backend, values in traces.items():
        rows[backend]['max_rel_err'], rows[backend]['worst_state'] = max_relative_error(
            values, traces[reference])
    return {'model': label, 'cellml': cellml_path, 'states': len(outputs),
            'reference': reference, 'backends': rows}


def markdown(report):
    settings = report['settings']
    lines = [
        f"Solver comparison: rtol {settings['rtol']:g}, atol {settings['atol']:g}, maximum step "
        f"{settings['max_step']:g} s, output every {settings['dt']:g} s; median of "
        f"{settings['repeats']} repeat runs. Python {report['python']}, {report['platform']}.",
        '',
        '| Model | States | Backend | Setup (s) | First run (s) | Run, median (s) | Steps | '
        'RHS evals | Max rel. error vs reference | In state |',
        '|---|---|---|---|---|---|---|---|---|---|',
    ]
    for model in report['models']:
        for backend, row in model['backends'].items():
            name = BACKENDS[backend][0] + (' (reference)' if backend == model['reference'] else '')
            if 'error' in row:
                lines.append(f"| {model['model']} | {model['states']} | {name} | "
                             f"failed: {row['error']} | | | | | | |")
                continue
            fmt = lambda v, f: '' if v is None else format(v, f)  # noqa: E731
            lines.append(
                f"| {model['model']} | {model['states']} | {name} | {row['setup_s']:.3f} | "
                f"{row['first_run_s']:.4f} | {row['run_median_s']:.4f} | "
                f"{fmt(row.get('steps'), 'd')} | {fmt(row.get('rhs_evals'), 'd')} | "
                f"{row['max_rel_err']:.1e} | {row['worst_state'] or ''} |")
    skipped = report['skipped_backends']
    if skipped:
        lines += ['', 'Skipped: ' + '; '.join(f'{b} ({why})' for b, why in skipped.items()) + '.']
    return '\n'.join(lines) + '\n'


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--models', default=','.join(MODELS),
                        help=f"comma-separated built-in models ({', '.join(MODELS)}), or '' for "
                             'none (default: all)')
    parser.add_argument('--model-file', action='append', default=[],
                        help='an external CellML file to compare too (repeatable)')
    parser.add_argument('--backends', default=','.join(BACKENDS),
                        help=f"comma-separated backends ({', '.join(BACKENDS)}); "
                             'missing ones are skipped')
    parser.add_argument('--reference', default='myokit',
                        help='backend the errors are measured against (default myokit, else '
                             'the first that ran)')
    parser.add_argument('--sim-time', type=float, default=None,
                        help="simulated seconds (default: each built-in model's own)")
    parser.add_argument('--dt', type=float, default=0.01, help='output interval (s)')
    parser.add_argument('--rtol', type=float, default=1e-6)
    parser.add_argument('--atol', type=float, default=1e-8)
    parser.add_argument('--max-step', type=float, default=1e-3)
    parser.add_argument('--repeats', type=int, default=3, help='timed repeat runs (at least 3)')
    parser.add_argument('--out', default=DEFAULT_OUT, help='directory for the JSON and Markdown')
    parser.add_argument('--work-dir', default=None,
                        help='where models are generated (default: a temporary directory)')
    parser.add_argument('--verbose', action='store_true', help="show the helpers' output")
    args = parser.parse_args(argv)
    if args.repeats < 3:
        parser.error('--repeats must be at least 3')
    unknown = [m for m in filter(None, args.models.split(',')) if m not in MODELS]
    unknown += [b for b in filter(None, args.backends.split(',')) if b not in BACKENDS]
    if unknown:
        parser.error(f'unknown model or backend: {unknown}')
    return args


def main(argv=None):
    args = parse_args(argv)
    requested = [b for b in args.backends.split(',') if b]
    status = available_backends(requested)
    backends = [b for b in requested if status[b] is None]
    skipped = {b: why for b, why in status.items() if why is not None}
    for backend, why in skipped.items():
        print(f'skipping {backend}: {why}')
    if not backends:
        print('no backend to run')
        return 1

    work_dir = args.work_dir or tempfile.mkdtemp(prefix='solver_comparison_')
    sim_time_arg = args.sim_time
    models = []
    jobs = [(name, None) for name in filter(None, args.models.split(','))]
    jobs += [(os.path.basename(path), os.path.abspath(path)) for path in args.model_file]
    for label, path in jobs:
        args.sim_time = sim_time_arg or (MODELS[label][2] if path is None else 10.0)
        print(f'{label} ({args.sim_time:g} s)', flush=True)
        with quiet(not args.verbose):
            cellml_path = path or cellml_for(label, work_dir)
        models.append({**compare_model(label, cellml_path, backends, args, work_dir),
                       'sim_time': args.sim_time})

    report = {
        'settings': {'rtol': args.rtol, 'atol': args.atol, 'max_step': args.max_step,
                     'dt': args.dt, 'repeats': args.repeats},
        'python': platform.python_version(), 'platform': platform.platform(),
        'skipped_backends': skipped, 'models': models,
    }
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, 'solver_comparison.json'), 'w') as f:
        json.dump(report, f, indent=1)
    table = markdown(report)
    with open(os.path.join(args.out, 'solver_comparison.md'), 'w') as f:
        f.write(table)
    print(table)
    return 0


if __name__ == '__main__':
    sys.exit(main())
